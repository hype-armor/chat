import { type Page, expect, test } from '@playwright/test'
import { conversationAction, randomUsername, signUp } from './support'

test.skip(!process.env.E2E_SERVER, 'needs chat-server and PostgreSQL (set E2E_SERVER=1 and DATABASE_URL)')

async function expectSingleRow(page: Page) {
  const header = page.locator('.conversation-bar')
  const title = await header.locator('.conversation-title').boundingBox()
  const actions = await header.locator('.header-actions').boundingBox()
  expect(title).not.toBeNull()
  expect(actions).not.toBeNull()
  expect(title!.x + title!.width).toBeLessThanOrEqual(actions!.x)
  expect(Math.abs(title!.y + title!.height / 2 - actions!.y - actions!.height / 2)).toBeLessThan(1)
  expect(actions!.x + actions!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
}

test('conversation menu supports keyboard, dismissal, actions and a 320px header', async ({ browser }) => {
  const username = randomUsername()
  const alice = await signUp(browser, 'Alice', randomUsername())
  await signUp(browser, 'Bob with a long display name', username)
  await alice.getByLabel("Contact's username").fill(username)
  await alice.getByRole('button', { name: 'Start chat' }).click()
  const trigger = alice.getByRole('button', { name: 'Conversation menu' })
  const menu = alice.getByRole('menu', { name: 'Conversation menu' })
  const items = menu.getByRole('menuitem')
  await expect(trigger).toHaveAttribute('aria-haspopup', 'menu')
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expectSingleRow(alice)
  await trigger.focus()
  await alice.keyboard.press('Enter')
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect(items).toHaveText(['Verify safety number', 'Add people', 'Report', 'Block'])
  await expect(items.first()).toBeFocused()
  await alice.keyboard.press('ArrowUp')
  await expect(items.last()).toBeFocused()
  await expect(items.last()).toHaveClass('danger')
  await alice.keyboard.press('ArrowDown')
  await expect(items.first()).toBeFocused()
  await alice.keyboard.press('End')
  await expect(items.last()).toBeFocused()
  await alice.keyboard.press('Home')
  await expect(items.first()).toBeFocused()
  await alice.keyboard.press('Escape')
  await expect(menu).toBeHidden()
  await expect(trigger).toBeFocused()
  await alice.keyboard.press('ArrowUp')
  await expect(items.last()).toBeFocused()
  await alice.keyboard.press('Escape')
  await alice.keyboard.press('ArrowDown')
  await expect(items.first()).toBeFocused()
  await alice.keyboard.press('Tab')
  await expect(menu).toBeHidden()
  await trigger.click()
  await alice.locator('.conversation-bar').click({ position: { x: 2, y: 2 } })
  await expect(menu).toBeHidden()
  await expect(trigger).toBeFocused()

  await conversationAction(alice, 'Verify safety number')
  await expect(menu).toBeHidden()
  await expect(trigger).toBeFocused()
  await expect(alice.getByTestId('safety-number')).toBeVisible()
  await alice.getByRole('button', { name: 'Mark as verified' }).click()
  await alice.setViewportSize({ width: 320, height: 640 })
  await expectSingleRow(alice)
  await expect(alice.getByRole('button', { name: 'Voice call', exact: true })).toBeVisible()
  await expect(alice.getByRole('button', { name: 'Video call', exact: true })).toBeVisible()
  await trigger.click()
  const bounds = await menu.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(320)
  await alice.keyboard.press('Escape')
  await alice.locator('.conversation-title').click()
  await expect(alice.getByTestId('safety-number')).toBeVisible()
  await conversationAction(alice, 'Add people')
  await expect(alice.getByLabel('Usernames to add')).toBeVisible()
  await conversationAction(alice, 'Block')
  await expect(alice.getByRole('note')).toContainText('You blocked')
  await trigger.click()
  await expect(items).toHaveText(['Verify safety number', 'Add people', 'Report'])
  await expect(alice.getByRole('button', { name: 'Voice call', exact: true })).toBeHidden()
})

test('group title opens info and the menu keeps group actions on one row', async ({ browser }) => {
  const username = randomUsername()
  const ann = await signUp(browser, 'Ann', randomUsername())
  await signUp(browser, 'Ben', username)
  await ann.getByText('New group').click()
  await ann.getByLabel('Group name').fill('A group with a very long title')
  await ann.getByLabel("Members' usernames").fill(username)
  await ann.getByRole('button', { name: 'Create group' }).click()
  await expect(ann.getByRole('heading', { name: 'A group with a very long title' })).toBeVisible()
  await expectSingleRow(ann)
  await ann.setViewportSize({ width: 320, height: 640 })
  await expectSingleRow(ann)
  await ann.locator('.conversation-title').click()
  await expect(ann.getByRole('button', { name: 'Rename', exact: true })).toBeVisible()
  await ann.getByRole('button', { name: 'Conversation menu' }).click()
  await expect(ann.getByRole('menuitem')).toHaveText(['Group info', 'Add people'])
  await ann.getByRole('menuitem', { name: 'Add people', exact: true }).click()
  await expect(ann.getByRole('menu')).toBeHidden()
  await expect(ann.getByLabel('Usernames to add')).toBeVisible()
})
