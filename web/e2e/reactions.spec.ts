    const actions = page.getByRole('menu', { name: 'Message actions', exact: true })
    await expect(actions.getByRole('menuitem', { name: 'Reply', exact: true })).toBeFocused()
    await page.keyboard.press('ArrowDown')
    await expect(actions.getByRole('menuitem', { name: 'React', exact: true })).toBeFocused()
    await page.keyboard.press('Enter')
    const picker = page.getByRole('menu', { name: 'Choose reaction', exact: true })
    await expect(picker.getByRole('menuitem', { name: 'Thumbs up', exact: true })).toBeFocused()
