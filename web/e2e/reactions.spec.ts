    await expect(own).toHaveAttribute('aria-pressed', 'true')
    await message.focus()
    await message.press('ContextMenu')
    await actions.getByRole('menuitem', { name: 'React', exact: true }).click()
    await picker.getByRole('menuitem', { name: 'Heart', exact: true }).click()
