    await page.setViewportSize({ width, height: 844 })
    await page.route('**/v1/**', (route) => route.abort('blockedbyclient'))
    await page.goto('/e2e/interactions-fixture.html?reactions=1')
    await page.getByRole('button', { name: /Bob/ }).click()
