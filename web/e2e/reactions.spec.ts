import { expect, test } from './fixtures'
import { fixtureAction, fixtureSend } from './interaction-fixture-support'

test.skip(!process.env.E2E_UI_FIXTURES, 'use playwright.fixtures.config.ts')

test('reaction picker fits a 250px visual viewport and keeps its final item reachable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.route('**/v1/**', (route) => route.abort('blockedbyclient'))
  await page.goto('/e2e/interactions-fixture.html?reactions=1')
  await page.getByRole('button', { name: /Bob/ }).click()
  await fixtureSend(page, 'Short viewport target')
  const message = page.getByTestId('message').filter({ hasText: 'Short viewport target' })
  await page.evaluate(() => {
    const viewport = window.visualViewport!
    Object.defineProperty(viewport, 'height', { configurable: true, value: 250 })
    Object.defineProperty(viewport, 'offsetTop', { configurable: true, value: 100 })
    viewport.dispatchEvent(new Event('resize'))
  })
  // Let keyboard-induced conversation scrolling finish before opening the menu.
  await expect.poll(() => page.locator('.messages-viewport').evaluate((el) => {
    const top = el.scrollTop
    return new Promise<boolean>((resolve) => requestAnimationFrame(() => requestAnimationFrame(() => resolve(el.scrollTop === top))))
  })).toBe(true)
  await message.focus()
  await message.press('Shift+F10')
  await page.getByRole('menuitem', { name: 'React', exact: true }).click()
  const picker = page.getByRole('menu', { name: 'Choose reaction', exact: true })
  await expect.poll(() => picker.evaluate((menu) => {
    const box = menu.getBoundingClientRect()
    return box.top >= 108 && box.bottom <= 342 && menu.scrollHeight > menu.clientHeight
  })).toBe(true)
  const firstItem = picker.getByRole('menuitem', { name: 'Thumbs up', exact: true })
  // Native touch scrolling can cancel its pointer without dismissing the menu.
  await firstItem.dispatchEvent('pointercancel', { pointerId: 21, pointerType: 'touch', isPrimary: true })
  await expect(picker).toBeVisible()
  await firstItem.focus()
  await page.keyboard.press('End')
  const finalItem = picker.getByRole('menuitem', { name: 'Thanks', exact: true })
  await expect(finalItem).toBeFocused()
  await expect.poll(() => finalItem.evaluate((item) => {
    const box = item.getBoundingClientRect()
    return box.top >= 108 && box.bottom <= 342
  })).toBe(true)
  await expect(picker).toBeVisible()
  await finalItem.press('Enter')
  await expect(message.getByRole('button', { name: 'Thanks, 1, remove your reaction', exact: true })).toBeVisible()
  await message.focus()
  await message.press('Shift+F10')
  await page.getByRole('menuitem', { name: 'React', exact: true }).click()
  await page.locator('.messages-viewport').evaluate((el) => el.dispatchEvent(new Event('scroll')))
  await expect(picker).toHaveCount(0)
})

test('reaction failure and removal failure expose explicit retry instead of silent confirmation', async ({ page }) => {
  await page.route('**/v1/**', (route) => route.abort('blockedbyclient'))
  await page.goto('/e2e/interactions-fixture.html?reactions=1')
  await page.getByRole('button', { name: /Bob/ }).click()
  await fixtureSend(page, 'Failure target')
  const message = page.getByTestId('message').filter({ hasText: 'Failure target' })
  await message.focus()
  await message.press('Shift+F10')
  await page.getByRole('menuitem', { name: 'React', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Heart', exact: true }).click()
  for (const removal of [false, true]) {
    if (removal) await message.getByRole('button', { name: 'Heart, 1, remove your reaction', exact: true }).click()
    await page.evaluate(() => (window as unknown as { interactionFixture: { failReaction(): void } }).interactionFixture.failReaction())
    await expect(message.getByRole('alert')).toContainText('Reaction not sent')
    await message.getByRole('button', { name: 'Retry reaction', exact: true }).click()
    await expect(message.getByRole('status')).toHaveText('Sending reaction…')
    await page.evaluate(() => (window as unknown as { interactionFixture: { acceptReaction(): void } }).interactionFixture.acceptReaction())
    await expect(message.getByRole('status')).toHaveCount(0)
    await expect(message.getByRole('alert')).toHaveCount(0)
  }
  await expect(message.getByRole('group', { name: 'Message reactions' })).toHaveCount(0)
})

test('renaming and blocking a direct chat disables existing own chips and reaction retry', async ({ page }) => {
  await page.route('**/v1/**', (route) => route.abort('blockedbyclient'))
  await page.goto('/e2e/interactions-fixture.html?reactions=1')
  await page.getByRole('button', { name: /Bob/ }).click()
  await fixtureSend(page, 'Blocked reaction target')
  const message = page.getByTestId('message').filter({ hasText: 'Blocked reaction target' })
  await message.focus()
  await message.press('Shift+F10')
  await page.getByRole('menuitem', { name: 'React', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Heart', exact: true }).click()
  const own = message.getByRole('button', { name: 'Heart, 1, remove your reaction', exact: true })
  await expect(own).toBeEnabled()
  await page.evaluate(() => {
    const fixture = (window as unknown as { interactionFixture: { failReaction(): void; blockRenamedDirect(): void } }).interactionFixture
    fixture.failReaction()
    fixture.blockRenamedDirect()
  })
  await expect(page.getByRole('note').filter({ hasText: 'You blocked Renamed direct chat' })).toBeVisible()
  await expect(own).toBeDisabled()
  await expect(message.getByRole('button', { name: 'Retry reaction', exact: true })).toBeDisabled()
  await expect(message).not.toHaveAttribute('aria-haspopup', 'menu')
})

