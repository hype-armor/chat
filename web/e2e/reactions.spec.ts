    await page.evaluate(() => (window as unknown as { interactionFixture: { seedReactions(): void } }).interactionFixture.seedReactions())
    await expect(message.getByRole('button', { name: 'Thumbs up, 2, react', exact: true })).toBeVisible()
    await message.click({ button: 'right' })
    await actions.getByRole('menuitem', { name: 'React', exact: true }).click()
    await picker.getByRole('menuitem', { name: 'Thumbs up', exact: true }).click()
