import { expect, test } from '@playwright/test'
import { createGroup, messages, randomUsername, signUp, startChat } from './support'

test.skip(!process.env.E2E_SERVER, 'needs chat-server and PostgreSQL (set E2E_SERVER=1 and DATABASE_URL)')

test('filters titles, usernames and requests locally and opens a keyboard result', async ({ browser }) => {
  const aliceUsername = randomUsername()
  const bobUsername = randomUsername()
  const alice = await signUp(browser, 'Álice', aliceUsername)
  const bob = await signUp(browser, 'Bob', bobUsername)
  await startChat(alice, bobUsername)
  await alice.getByLabel('Message', { exact: true }).fill('Not a searchable preview')
  await alice.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(alice.getByRole('heading', { name: 'Bob', exact: true })).toBeVisible()

  const requests = bob.getByRole('navigation', { name: 'Requests', exact: true })
  await expect(requests.getByRole('button', { name: /Álice/, includeHidden: true })).toBeAttached()
  const bobSearch = bob.getByRole('searchbox', { name: 'Search conversations' })
  await bobSearch.fill('ALICE')
  await expect(requests.getByRole('button', { name: /Álice/ })).toBeVisible()
  await expect(requests.locator('mark')).toHaveText('Álice')
  await bobSearch.press('ArrowDown')
  await expect(requests.getByRole('button', { name: /Álice/ })).toBeFocused()
  await bob.keyboard.press('Enter')
  await bob.getByRole('button', { name: 'Accept', exact: true }).click()
  await expect(messages(bob)).toHaveText([/Not a searchable preview/])

  await createGroup(alice, 'Café Équipe', [bobUsername])
  const nav = alice.getByRole('navigation', { name: 'Conversations', exact: true })
  const rows = nav.locator('.conversations button')
  const search = alice.getByRole('searchbox', { name: 'Search conversations' })
  await alice.getByRole('button', { name: 'Settings', exact: true }).focus()
  await alice.keyboard.press('/')
  await expect(search).toBeFocused()
  await search.fill('CAFE')
  await expect(rows).toHaveCount(1)
  await expect(rows.locator('mark')).toHaveText('Café')
  await search.press('ArrowDown')
  await expect(rows).toBeFocused()
  await alice.keyboard.press('Escape')
  await expect(search).toBeFocused()
  await expect(search).toHaveValue('')
  await expect(rows).toHaveCount(2)

  await search.fill(bobUsername.toUpperCase())
  await expect(rows).toHaveCount(1)
  await expect(rows).toContainText('Bob')
  await search.press('ArrowUp')
  await alice.keyboard.press('Enter')
  await expect(alice.getByRole('heading', { name: 'Bob', exact: true })).toBeVisible()
  await nav.getByRole('button', { name: 'Clear search' }).click()
  await expect(rows).toHaveCount(2)
  const composer = alice.getByLabel('Message', { exact: true })
  await composer.fill('/')
  await expect(search).not.toBeFocused()
  await composer.press('ControlOrMeta+k')
  await expect(search).toBeFocused()
  await search.fill('Not a searchable preview')
  await expect(rows).toHaveCount(0)
  await expect(nav.getByRole('status')).toHaveText('No chats match "Not a searchable preview"')
  await expect(nav.getByRole('button', { name: /Start a chat with/ })).toHaveCount(0)

  const carolUsername = randomUsername()
  await signUp(browser, 'Carol', carolUsername)
  await search.fill(carolUsername)
  await nav.getByRole('button', { name: `Start a chat with ${carolUsername}` }).click()
  await expect(alice.getByRole('heading', { name: carolUsername, exact: true })).toBeVisible()
})

test('search stays compact and opens a filtered chat on a phone', async ({ browser }) => {
  const alice = await signUp(browser, 'Alice', randomUsername())
  await alice.setViewportSize({ width: 360, height: 720 })
  await startChat(alice, 'echo.00')
  await expect(alice.getByRole('heading', { name: 'Echo (test bot)', exact: true })).toBeVisible()
  await alice.getByRole('button', { name: 'Back to conversations', exact: true }).click()
  const search = alice.getByRole('searchbox', { name: 'Search conversations' })
  await search.fill('ECHO')
  const nav = alice.getByRole('navigation', { name: 'Conversations', exact: true })
  await expect(nav.locator('mark')).toHaveText('Echo')
  await nav.getByRole('button', { name: /Echo \(test bot\)/ }).click()
  await expect(alice.getByLabel('Message', { exact: true })).toBeVisible()
  expect(await alice.locator('html').evaluate((element) => element.scrollWidth)).toBe(360)
})
