import { test, expect } from './fixtures'

test.skip(!process.env.E2E_UI_FIXTURES, 'needs the Vite UI fixture server')

for (const width of [390, 1280]) test(`creates and invites private channels at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 844 })
  await page.route('**/v1/**', (route) => route.abort('blockedbyclient'))
  await page.goto('/e2e/interactions-fixture.html?channels=1&title=Parent%20group')
  await page.getByRole('button', { name: /Parent group/ }).click()
  await page.getByRole('button', { name: 'Conversation menu' }).click()
  await page.getByRole('menuitem', { name: 'Group info', exact: true }).click()
  await page.getByRole('button', { name: 'Create private channel', exact: true }).click()
  const form = page.getByRole('form', { name: 'Create private channel' })
  await expect(form.getByText('Some members have no cached current username.', { exact: false })).toBeVisible()
  await form.getByLabel('Channel name').fill('Private planning')
  await expect(form.getByRole('button', { name: 'Create private channel' })).toBeDisabled()
  await form.getByRole('checkbox', { name: 'Bob (@Bob.02)' }).check()
  await expect(form.getByRole('checkbox')).toHaveCount(1)
  await form.getByRole('button', { name: 'Create private channel' }).click()
  await expect(page.getByRole('heading', { name: 'Private planning', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Add attachment' })).toHaveCount(0)
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('Preserved channel draft')
  await page.getByRole('button', { name: 'Conversation menu' }).click()
  await expect(page.getByRole('menuitem', { name: 'Add people', exact: true })).toHaveCount(0)
  await page.getByRole('menuitem', { name: 'Invite to private channel', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit group name' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Leave group', exact: true })).toHaveCount(0)
  const invitation = page.getByRole('form', { name: 'Invite to private channel' })
  await invitation.getByRole('checkbox', { name: 'Bob (@Bob.02)' }).check()
  await invitation.getByRole('button', { name: 'Invite members' }).click()
  const requests = await page.evaluate(() => (window as unknown as { interactionFixture: { channelRequests: unknown[] } }).interactionFixture.channelRequests)
  expect(requests).toEqual([
    { type: 'create', parentId: 'chat', name: 'Private planning', usernames: ['Bob.02'] },
    { type: 'invite', channelId: 'private-child', usernames: ['Bob.02'] },
  ])
  await page.getByRole('button', { name: 'Conversation menu' }).click()
  await page.getByRole('menuitem', { name: 'Group info', exact: true }).click()
  await page.getByRole('button', { name: 'Parent group', exact: true }).click()
  await page.getByRole('button', { name: 'Conversation menu' }).click()
  await page.getByRole('menuitem', { name: 'Group info', exact: true }).click()
  await page.getByRole('region', { name: 'Private channels', exact: true }).getByRole('button', { name: 'Private planning' }).click()
  await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toHaveValue('Preserved channel draft')
  await page.evaluate(() => (window as unknown as { interactionFixture: { pauseChannel(): void } }).interactionFixture.pauseChannel())
  await expect(page.getByText('Channel sending is paused', { exact: false })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toBeHidden()
})

test('default groups do not advertise private channel creation', async ({ page }) => {
  await page.route('**/v1/**', (route) => route.abort('blockedbyclient'))
  await page.goto('/e2e/interactions-fixture.html?group=1&title=Ordinary%20group')
  await page.getByRole('button', { name: /Ordinary group/ }).click()
  await page.getByRole('button', { name: 'Conversation menu' }).click()
  await page.getByRole('menuitem', { name: 'Group info', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Private channels', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '＋ Add people' })).toBeVisible()
})
